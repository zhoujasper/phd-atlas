function defineProfile({
  id,
  label,
  domain,
  match,
  canonical,
  related = [],
  providers = [],
  vocabularies = [],
}) {
  return Object.freeze({
    id,
    label,
    domain,
    match,
    canonical,
    related: Object.freeze(related),
    providers: Object.freeze(['openalex', 'crossref', ...providers]),
    vocabularies: Object.freeze(vocabularies),
  })
}

