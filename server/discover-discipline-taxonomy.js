function splitTerms(value) {
  return String(value || '')
    .split(/[\n,，、;；|/]+/)
    .map((term) => term.replace(/\s+/g, ' ').trim())
    .filter(Boolean)
}

function matchingProfiles(value) {
  return DISCOVER_DISCIPLINE_PROFILES.filter((profile) => profile.match.test(String(value || '')))
}

export function discoverDisciplineExpansionForTerm(value) {
  const profiles = matchingProfiles(value)
  return {
    canonical: [...new Set(profiles.map((profile) => profile.canonical).filter(Boolean))],
    related: [...new Set(profiles.flatMap((profile) => profile.related || []).filter(Boolean))],
    profileIds: profiles.map((profile) => profile.id),
  }
}

/**
 * Pick one precise canonical seed per user-supplied direction before adding
 * adjacent terminology. This prevents a long specialist list in the first
 * discipline from consuming the complete dynamic-topic budget.
 */
export function buildDiscoverDisciplineQuerySeeds(values, { limit = 12 } = {}) {
  const terms = (Array.isArray(values) ? values : [values]).flatMap(splitTerms)
  const boundedLimit = Math.max(1, Math.min(16, Number(limit) || 12))
  const expansions = terms.map((term) => ({
    term,
    ...discoverDisciplineExpansionForTerm(term),
  }))
  const output = []
  const seen = new Set()
  const add = (value) => {
    const term = String(value || '').replace(/\s+/g, ' ').trim().slice(0, 120)
    const key = term.normalize('NFKC').toLocaleLowerCase()
    if (!term || seen.has(key) || output.length >= boundedLimit) return
    seen.add(key)
    output.push(term)
  }
  for (const expansion of expansions) add(expansion.canonical[0] || expansion.term)
  const maxCanonicalDepth = Math.max(0, ...expansions.map((expansion) => expansion.canonical.length))
  for (let depth = 1; depth < maxCanonicalDepth && output.length < boundedLimit; depth += 1) {
    for (const expansion of expansions) add(expansion.canonical[depth])
  }
  const maxRelatedDepth = Math.max(0, ...expansions.map((expansion) => expansion.related.length))
  for (let depth = 0; depth < maxRelatedDepth && output.length < boundedLimit; depth += 1) {
    for (const expansion of expansions) add(expansion.related[depth])
  }
  return output
}

export function buildDiscoverDisciplinePlan(values) {
  const terms = (Array.isArray(values) ? values : [values]).flatMap(splitTerms)
  const matches = []
  const seen = new Set()
  for (const term of terms) {
    for (const profile of matchingProfiles(term)) {
      if (seen.has(profile.id)) continue
      seen.add(profile.id)
      matches.push(profile)
    }
  }
  const broadDomainIds = [...new Set(matches.map((profile) => profile.domain))]
  return {
    taxonomyVersion: DISCOVER_DISCIPLINE_TAXONOMY_VERSION,
    broadDomains: broadDomainIds.map((id) => ({ id, label: FORD_DOMAINS[id] })),
    disciplines: matches.map((profile) => ({
      id: profile.id,
      label: profile.label,
      broadDomain: profile.domain,
      canonicalTerm: profile.canonical,
      providers: profile.providers,
      vocabularies: profile.vocabularies,
    })),
    canonicalTerms: [...new Set(matches.map((profile) => profile.canonical).filter(Boolean))],
    relatedTerms: [...new Set(matches.flatMap((profile) => profile.related || []).filter(Boolean))],
    providerHints: [...new Set(['openalex', 'crossref', ...matches.flatMap((profile) => profile.providers)])],
    vocabularies: [...new Set(matches.flatMap((profile) => profile.vocabularies))],
    sources: DISCOVER_DISCIPLINE_SOURCES,
  }
}
